use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let _ = embed_resource::compile("./buildrc/redreply.rc", embed_resource::NONE);

    // ===== 编译时嵌入项目源码，供 LLM 或用户随时翻阅 =====
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut files: Vec<(String, Vec<u8>)> = Vec::new();

    fn collect_dir(dir: &Path, prefix: &str, files: &mut Vec<(String, Vec<u8>)>) {
        if !dir.is_dir() {
            return;
        }
        let entries = match fs::read_dir(dir) {
            Ok(e) => e,
            Err(_) => return,
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let name = entry.file_name().to_string_lossy().to_string();
            if matches!(
                name.as_str(),
                "target" | ".git" | "node_modules" | "__pycache__" | "crash"
            ) {
                continue;
            }
            let rel = format!("{prefix}/{name}");
            if path.is_dir() {
                collect_dir(&path, &rel, files);
            } else if path.is_file() {
                if let Ok(data) = fs::read(&path) {
                    files.push((rel, data));
                }
            }
        }
    }

    collect_dir(&root.join("src"), "src", &mut files);
    collect_dir(&root.join("crates"), "crates", &mut files);
    collect_dir(&root.join("res"), "res", &mut files);
    collect_dir(&root.join("docs"), "docs", &mut files);
    for single in ["Cargo.toml", "readme.md", "build.rs", "buildrc/redreply.rc"] {
        let p = root.join(single);
        if let Ok(data) = fs::read(&p) {
            files.push((single.to_string(), data));
        }
    }

    let mut out = String::from("// @generated by build.rs - do not edit\n");
    out.push_str("pub const SOURCE_FILES: &[(&str, &str)] = &[\n");
    for (path, data) in &files {
        match std::str::from_utf8(data) {
            Ok(s) => {
                out.push_str(&format!("    ({:?}, {:?}),\n", path, s));
            }
            Err(_) => {
                // 非 UTF-8 文件（如二进制资源）跳过
                continue;
            }
        }
    }
    out.push_str("];\n");

    let out_dir = env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("embedded_source.rs"), out).unwrap();

    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=crates");
    println!("cargo:rerun-if-changed=res");
    println!("cargo:rerun-if-changed=docs");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-changed=readme.md");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=buildrc");
}
